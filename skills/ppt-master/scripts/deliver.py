#!/usr/bin/env python3
"""
PPT Master - Delivery Packaging Tool

Turns a finished working project into one plain delivery folder and back.

    <title>/
      <title>.pptx            final deck, local fonts embedded
      制作文件/                only what a later revision needs
        使用说明.md
        演讲稿.md              notes/total.md
        幻灯片页面/            svg_output/
        设计规范/              design_spec.md, spec_lock.md, animations.json
        图标/  图片/  原始资料/  模板/  资料分析/   (only when non-empty)

Everything else in the working project (backup/, svg_final/, split notes,
validation/, confirm_ui/, live_preview/, older exports) is regenerated by the
pipeline and is removed with the working project after a verified copy.

Usage:
    python3 scripts/deliver.py pack <project_path> --title "<deck title>"
    python3 scripts/deliver.py pack <project_path> --title "..." --pptx <file> --dest <dir>
    python3 scripts/deliver.py unpack <delivery_folder>

Notes:
    - pack picks the newest exports/*.pptx unless --pptx is given, embeds local
      fonts (pptx_embed_fonts.py) unless --no-embed-fonts, writes the folder
      next to projects/ unless --dest is given, and replaces an earlier delivery
      of the same title in place (files the user added there are kept).
    - unpack rebuilds projects/<original dir name>/ from 制作文件/ so the
      revision round can edit and re-export; pack again afterwards.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

WORK_DIRNAME = "制作文件"
MANIFEST_NAME = ".ppt-master.json"
NOTES_NAME = "演讲稿.md"
GUIDE_NAME = "使用说明.md"

# project path -> delivery path (directories copied whole when non-empty)
DIR_MAP = {
    "svg_output": "幻灯片页面",
    "icons": "图标",
    "images": "图片",
    "sources": "原始资料",
    "templates": "模板",
    "analysis": "资料分析",
}
SPEC_DIR = "设计规范"
SPEC_FILES = ("design_spec.md", "spec_lock.md", "animations.json")

# Directories an initialized project carries (project_manager init).
SKELETON = ("svg_output", "svg_final", "images", "icons", "notes", "templates",
            "live_preview", "sources", "analysis", "validation", "exports")

_JUNK = {".DS_Store", "Thumbs.db", "desktop.ini"}


def _files(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*") if p.is_file() and p.name not in _JUNK)


def _non_empty(path: Path) -> bool:
    return path.is_dir() and bool(_files(path))


def _safe_title(title: str) -> str:
    cleaned = re.sub(r'[\\/:*?"<>|\x00-\x1f]', " ", title).strip().strip(".")
    cleaned = re.sub(r"\s+", " ", cleaned)
    if not cleaned:
        raise SystemExit("--title is empty after removing characters a file name cannot hold")
    return cleaned


def _guide(title: str, kept: list[str]) -> str:
    rows = {
        "幻灯片页面": "每一页幻灯片的 SVG 源文件，改版式、改文字都在这里",
        SPEC_DIR: "配色、字体、字号和每页规划（design_spec.md / spec_lock.md），动画设置（animations.json）",
        "图标": "页面里用到的图标",
        "图片": "页面里用到的图片",
        "原始资料": "最初提供的大纲、文档等资料",
        "模板": "套用的模板文件",
        "资料分析": "导入资料时自动提取的分析结果",
    }
    lines = [
        f"# {title} · 制作文件",
        "",
        f"外层的「{title}.pptx」是定稿。这个文件夹只放以后修改 PPT 要用到的东西：",
        "",
        f"- `{NOTES_NAME}`：逐页演讲稿（PPT 备注里也有一份）",
    ]
    lines += [f"- `{name}/`：{rows[name]}" for name in kept if name in rows]
    lines += [
        "",
        "## 要改 PPT 时",
        "",
        "对 Claude 说「用 ppt-master 修改 <这个文件夹的路径>」，它会从这里恢复工程、改完重新导出。",
        "",
        "## 定稿以后",
        "",
        "确定不再修改，可以把整个「制作文件」文件夹删掉，PPT 本身不受影响。",
        "",
    ]
    return "\n".join(lines)


def _pick_pptx(project: Path, explicit: Path | None) -> Path:
    if explicit:
        if not explicit.is_file():
            raise SystemExit(f"--pptx not found: {explicit}")
        return explicit
    exports = sorted((project / "exports").glob("*.pptx"), key=lambda p: p.stat().st_mtime)
    if not exports:
        raise SystemExit(f"no PPTX in {project / 'exports'}; run svg_to_pptx.py first")
    return exports[-1]


def pack(args: argparse.Namespace) -> int:
    project = args.project.resolve()
    if not (project / "svg_output").is_dir():
        raise SystemExit(f"not a ppt-master project (no svg_output/): {project}")
    title = _safe_title(args.title)
    source_pptx = _pick_pptx(project, args.pptx)

    if args.dest:
        dest_root = args.dest.resolve()
    elif project.parent.name == "projects":
        dest_root = project.parent.parent
    else:
        dest_root = project.parent
    delivery = dest_root / title
    if delivery.resolve() == project or project in delivery.resolve().parents:
        raise SystemExit("delivery folder must be outside the working project")
    delivery.mkdir(parents=True, exist_ok=True)

    staging = delivery / f".{WORK_DIRNAME}.tmp"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir()

    # 1. Revision inputs.
    kept: list[str] = []
    expected: dict[str, int] = {}
    for src_name, dst_name in DIR_MAP.items():
        src = project / src_name
        if src_name == "svg_output" or _non_empty(src):
            shutil.copytree(src, staging / dst_name,
                            ignore=shutil.ignore_patterns(*_JUNK))
            kept.append(dst_name)
            expected[dst_name] = len(_files(src))
    spec_dir = staging / SPEC_DIR
    for name in SPEC_FILES:
        if (project / name).is_file():
            spec_dir.mkdir(exist_ok=True)
            shutil.copy2(project / name, spec_dir / name)
    if spec_dir.is_dir():
        kept.insert(1, SPEC_DIR)
        expected[SPEC_DIR] = len(_files(spec_dir))
    total_md = project / "notes" / "total.md"
    if total_md.is_file():
        shutil.copy2(total_md, staging / NOTES_NAME)

    readme = project / "README.md"
    manifest = {
        "format": 1,
        "project_dir": project.name,
        "title": title,
        "dirs": {v: k for k, v in DIR_MAP.items()},
        "spec_dir": SPEC_DIR,
        "notes": NOTES_NAME,
        "readme": readme.read_text(encoding="utf-8") if readme.is_file() else "",
    }
    (staging / MANIFEST_NAME).write_text(json.dumps(manifest, ensure_ascii=False, indent=2),
                                         encoding="utf-8")
    (staging / GUIDE_NAME).write_text(_guide(title, kept), encoding="utf-8")

    for name, count in expected.items():
        got = len(_files(staging / name))
        if got != count:
            shutil.rmtree(staging)
            raise SystemExit(f"copy check failed for {name}: {got} of {count} files; nothing removed")

    # 2. Final deck at the top level.
    final_pptx = delivery / f"{title}.pptx"
    tmp_pptx = delivery / f".{title}.tmp.pptx"
    if args.no_embed_fonts:
        shutil.copy2(source_pptx, tmp_pptx)
    else:
        embed = Path(__file__).with_name("pptx_embed_fonts.py")
        cmd = [sys.executable, str(embed), str(source_pptx), "-o", str(tmp_pptx)]
        for d in args.font_dir:
            cmd += ["--font-dir", d]
        if subprocess.run(cmd).returncode != 0:
            shutil.rmtree(staging)
            raise SystemExit("font embedding failed; nothing replaced or removed")
    os.replace(tmp_pptx, final_pptx)

    # 3. Swap in the new 制作文件.
    work = delivery / WORK_DIRNAME
    if work.exists():
        shutil.rmtree(work)
    os.replace(staging, work)

    # 4. Drop the working project; everything else in it is regenerable.
    removed = ""
    if not args.keep_workdir:
        size = sum(p.stat().st_size for p in project.rglob("*") if p.is_file())
        count = len(_files(project))
        shutil.rmtree(project)
        removed = f"removed working project ({count} files, {size / 1024 / 1024:.1f} MB)"
        parent = project.parent
        if parent.name == "projects" and all(p.name in _JUNK for p in parent.iterdir()):
            shutil.rmtree(parent)
            removed += " and the empty projects/ folder"

    print(f"[DELIVER] {delivery}")
    print(f"  {final_pptx.name}  ({final_pptx.stat().st_size / 1024 / 1024:.1f} MB, from {source_pptx.name})")
    print(f"  {WORK_DIRNAME}/  {len(_files(work))} files: " + ", ".join([NOTES_NAME] + kept))
    if removed:
        print(f"  {removed}")
    return 0


def unpack(args: argparse.Namespace) -> int:
    delivery = args.delivery.resolve()
    work = delivery / WORK_DIRNAME if (delivery / WORK_DIRNAME).is_dir() else delivery
    manifest_path = work / MANIFEST_NAME
    if not manifest_path.is_file():
        raise SystemExit(f"no {MANIFEST_NAME} in {work}; not a ppt-master delivery folder")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    projects_dir = (args.projects_dir or delivery.parent / "projects").resolve()
    project = projects_dir / manifest["project_dir"]
    if project.exists():
        raise SystemExit(f"working project already exists: {project}")
    for name in SKELETON:
        (project / name).mkdir(parents=True, exist_ok=True)

    for dst_name, src_name in manifest["dirs"].items():
        src = work / dst_name
        if src.is_dir():
            shutil.copytree(src, project / src_name, dirs_exist_ok=True)
    spec_dir = work / manifest["spec_dir"]
    if spec_dir.is_dir():
        for f in spec_dir.iterdir():
            if f.is_file() and f.name not in _JUNK:
                shutil.copy2(f, project / f.name)
    notes = work / manifest["notes"]
    if notes.is_file():
        shutil.copy2(notes, project / "notes" / "total.md")
    if manifest.get("readme"):
        (project / "README.md").write_text(manifest["readme"], encoding="utf-8")

    print(f"[UNPACK] {project}")
    print("  next: edit, rerun the final quality gate, 7.1-7.3, then deliver.py pack again")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Package a finished project into one delivery folder.")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("pack", help="build <title>/ with the final deck and 制作文件/")
    p.add_argument("project", type=Path)
    p.add_argument("--title", required=True, help="deck title; names the folder and the .pptx")
    p.add_argument("--pptx", type=Path, help="deck to deliver (default: newest in exports/)")
    p.add_argument("--dest", type=Path, help="parent folder (default: next to projects/)")
    p.add_argument("--no-embed-fonts", action="store_true")
    p.add_argument("--font-dir", action="append", default=[])
    p.add_argument("--keep-workdir", action="store_true", help="do not remove the working project")
    p.set_defaults(func=pack)

    u = sub.add_parser("unpack", help="rebuild projects/<name>/ from a delivery folder")
    u.add_argument("delivery", type=Path)
    u.add_argument("--projects-dir", type=Path)
    u.set_defaults(func=unpack)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
